#!/usr/bin/env python3
"""Writes certs.h: the root certificates Cloudflare's edge certificates chain to (Google Trust Services, Let's
Encrypt, SSL.com), taken from the system bundle, for the screen to check the server it streams from."""
import re, sys

BUNDLE = sys.argv[1] if len(sys.argv) > 1 else "/etc/ssl/cert.pem"
WANTED = ["GTS Root R1", "GTS Root R2", "GTS Root R3", "GTS Root R4", "ISRG Root X1", "ISRG Root X2",
          "SSL.com Root Certification Authority RSA", "SSL.com Root Certification Authority ECC",
          "SSL.com TLS RSA Root CA 2022", "SSL.com TLS ECC Root CA 2022"]
text = open(BUNDLE).read()
found = {}
for section in text.split("\n=== ")[1:]:
    name = re.search(r"CN=([^/\n]+)", section.split("\n", 1)[0])
    pem = re.search(r"-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----", section, re.S)
    if name and pem and name.group(1).strip() in WANTED:
        found[name.group(1).strip()] = pem.group(0)
missing = [n for n in WANTED if n not in found]
lines = ["// Generated by certs.py from the system bundle: the roots behind Cloudflare's edge certificates.",
         "// " + ", ".join(sorted(found)), "#pragma once", "static const char ROOT_CAS[] PROGMEM ="]
for pem in found.values():
    lines += [f'  "{l}\\n"' for l in pem.splitlines()]
lines[-1] += ";"
open("certs.h", "w").write("\n".join(lines) + "\n")
print(f"certs.h: {len(found)} roots; missing: {', '.join(missing) or 'none'}")
